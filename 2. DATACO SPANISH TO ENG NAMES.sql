-- ---------------------------------------------------------------------
-- 2) Customer country: 'EE. UU.' is Spanish for United States
-- ---------------------------------------------------------------------
UPDATE dim_customer_country SET customer_country = 'United States' WHERE customer_country = 'EE. UU.';

-- ---------------------------------------------------------------------
-- 3) Region names have extra spaces ('West of USA ', 'South of  USA ')
-- ---------------------------------------------------------------------
UPDATE dim_order_region SET order_region = TRIM(REPLACE(order_region, '  ', ' '));

-- ---------------------------------------------------------------------
-- 4) 3 customers are shifted one column in the CSV:
--    state holds the zipcode ('95758'), city holds 'CA', street holds the real city ('Elk Grove')
-- ---------------------------------------------------------------------
-- 4a. make sure the real (state, city) pairs exist
INSERT IGNORE INTO dim_customer_city (customer_city, customer_state_key)
SELECT DISTINCT c.street, good.customer_state_key
FROM dim_customer c
JOIN dim_customer_city ci ON ci.customer_city_key = c.customer_city_key
JOIN dim_customer_state bad ON bad.customer_state_key = ci.customer_state_key
JOIN dim_customer_state good ON good.customer_state = ci.customer_city
WHERE bad.customer_state REGEXP '^[0-9]+$';

-- 4b. point the customers at the right city, move the zipcode, clear the street
UPDATE dim_customer c
JOIN dim_customer_city ci ON ci.customer_city_key = c.customer_city_key
JOIN dim_customer_state bad ON bad.customer_state_key = ci.customer_state_key
JOIN dim_customer_state good ON good.customer_state = ci.customer_city
JOIN dim_customer_city fix ON fix.customer_state_key = good.customer_state_key AND fix.customer_city = c.street
SET c.customer_city_key = fix.customer_city_key, c.zipcode = bad.customer_state, c.street = NULL
WHERE bad.customer_state REGEXP '^[0-9]+$';

-- 4c. remove the fake city and state rows nobody uses anymore
DELETE ci FROM dim_customer_city ci
JOIN dim_customer_state s ON s.customer_state_key = ci.customer_state_key
WHERE s.customer_state REGEXP '^[0-9]+$';
DELETE FROM dim_customer_state WHERE customer_state REGEXP '^[0-9]+$';

